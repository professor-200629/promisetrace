import { z } from "zod";
import { isSupportedCurrency } from "@/lib/money";

/**
 * Structured brief stored in BriefVersion.content.
 * Every claim carries `refs` (exact passages in a SourceDocument, by offsets)
 * and a `status`:
 *  - sourced: value supported by at least one verified passage
 *  - unknown: nothing in the sources states it
 *  - needs_clarification: sources mention it but ambiguously
 *  - edited: a participant changed it after extraction (refs show the original passage)
 */
export const SourceRefSchema = z.object({
  source: z.string().min(1).max(8), // "S1"
  start: z.number().int().nonnegative(),
  end: z.number().int().positive(),
  quote: z.string().min(1).max(600),
});
export type SourceRef = z.infer<typeof SourceRefSchema>;

export const ClaimStatus = z.enum(["sourced", "unknown", "needs_clarification", "edited"]);
export type ClaimStatus = z.infer<typeof ClaimStatus>;

const Meta = {
  refs: z.array(SourceRefSchema).max(6),
  status: ClaimStatus,
  editedBy: z.enum(["SELLER", "BUYER"]).optional(),
};

export const FILE_FORMATS = ["png", "svg", "pdf", "jpeg", "zip", "ai", "eps", "psd", "fig", "mp4", "docx", "txt"] as const;
export const CHECKABLE_FORMATS = new Set(["png", "svg", "pdf", "jpeg", "zip"]);

export const DeliverableSchema = z.object({
  key: z.string().regex(/^D\d{1,2}$/),
  label: z.string().min(1).max(120),
  quantity: z.number().int().positive().max(100).nullable(),
  formats: z.array(z.enum(FILE_FORMATS)).max(6),
  ...Meta,
});
export type Deliverable = z.infer<typeof DeliverableSchema>;

export const OpenQuestionSchema = z.object({
  key: z.string().regex(/^Q\d{1,2}$/),
  text: z.string().min(1).max(300),
  origin: z.enum(["AI", "CHECK"]), // CHECK = generated by deterministic code
  refs: z.array(SourceRefSchema).max(4),
});
export type OpenQuestion = z.infer<typeof OpenQuestionSchema>;

export const BriefContentSchema = z.object({
  title: z.string().min(1).max(120),
  price: z.object({
    amountMinor: z.number().int().positive().nullable(),
    currency: z.string().length(3).nullable().refine((c) => c === null || isSupportedCurrency(c), "Currency not supported by PayPal Checkout"),
    ...Meta,
  }),
  deadline: z.object({
    date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).nullable(),
    time: z.string().regex(/^\d{2}:\d{2}$/).nullable(),
    timezone: z.string().max(64).nullable(),
    ...Meta,
  }),
  revisionRounds: z.object({
    count: z.number().int().nonnegative().max(20).nullable(),
    ...Meta,
  }),
  deliverables: z.array(DeliverableSchema).max(12),
  openQuestions: z.array(OpenQuestionSchema).max(12),
});
export type BriefContent = z.infer<typeof BriefContentSchema>;

export function isValidTimeZone(tz: string): boolean {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: tz });
    return true;
  } catch {
    return false;
  }
}

/** Offset (ms) of `tz` at the given UTC instant. */
function tzOffsetMs(utcMs: number, tz: string): number {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: tz, hourCycle: "h23", year: "numeric", month: "2-digit", day: "2-digit",
    hour: "2-digit", minute: "2-digit", second: "2-digit",
  }).formatToParts(new Date(utcMs));
  const get = (t: string) => Number(parts.find((p) => p.type === t)?.value);
  const asUtc = Date.UTC(get("year"), get("month") - 1, get("day"), get("hour"), get("minute"), get("second"));
  return asUtc - utcMs;
}

/**
 * Deterministic deadline instant. If no time was agreed, end of day (23:59)
 * in the agreed timezone is used and `assumedTime` is true so the UI can say so.
 */
export function deadlineInstant(d: BriefContent["deadline"]): { utc: Date; assumedTime: boolean } | null {
  if (!d.date || !d.timezone || !isValidTimeZone(d.timezone)) return null;
  const [y, m, day] = d.date.split("-").map(Number) as [number, number, number];
  const [hh, mm] = (d.time ?? "23:59").split(":").map(Number) as [number, number];
  const naive = Date.UTC(y, m - 1, day, hh, mm, 0);
  let utc = naive - tzOffsetMs(naive, d.timezone);
  utc = naive - tzOffsetMs(utc, d.timezone); // second pass handles DST edges
  return { utc: new Date(utc), assumedTime: d.time === null };
}

/**
 * Code-generated clarification questions for gaps that block checking or
 * payment. These are labelled origin "CHECK" so the UI can tell them apart
 * from questions the AI proposed.
 */
export function gapQuestions(b: BriefContent): Array<Omit<OpenQuestion, "key">> {
  const q: Array<Omit<OpenQuestion, "key">> = [];
  if (b.price.amountMinor === null || b.price.currency === null) {
    q.push({ text: "What is the agreed total price and currency?", origin: "CHECK", refs: [] });
  }
  if (b.deadline.date === null) {
    q.push({ text: "What is the delivery deadline (date)?", origin: "CHECK", refs: [] });
  } else if (b.deadline.timezone === null) {
    q.push({ text: `Which timezone applies to the ${b.deadline.date} deadline?`, origin: "CHECK", refs: b.deadline.refs.slice(0, 1) });
  }
  if (b.revisionRounds.count === null) {
    q.push({ text: "How many revision rounds are included?", origin: "CHECK", refs: [] });
  }
  for (const d of b.deliverables) {
    if (d.formats.length === 0 && d.quantity === null) {
      q.push({ text: `What exactly is delivered for "${d.label}" (how many, which file formats)?`, origin: "CHECK", refs: d.refs.slice(0, 1) });
    }
  }
  return q;
}

/** Returns blocking problems that prevent approval for payment. */
export function paymentBlockers(b: BriefContent): string[] {
  const out: string[] = [];
  if (b.price.amountMinor === null || b.price.currency === null) out.push("Price and currency must be set.");
  if (b.deliverables.length === 0) out.push("At least one deliverable must be listed.");
  return out;
}

export function emptyBrief(title: string): BriefContent {
  return {
    title,
    price: { amountMinor: null, currency: null, refs: [], status: "unknown" },
    deadline: { date: null, time: null, timezone: null, refs: [], status: "unknown" },
    revisionRounds: { count: null, refs: [], status: "unknown" },
    deliverables: [],
    openQuestions: [],
  };
}

export function renumberQuestions(qs: Array<Omit<OpenQuestion, "key">>): OpenQuestion[] {
  return qs.slice(0, 12).map((q, i) => ({ ...q, key: `Q${i + 1}` }));
}
